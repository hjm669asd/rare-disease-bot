# pathlib.Path 是 Python 标准库中处理文件路径的工具。
# 相比直接写字符串路径，Path 更适合跨平台路径拼接。
from pathlib import Path


# BASE_DIR 表示当前脚本所在目录。
# 当前文件位于：2.文档切分与检索效果/examples。
BASE_DIR = Path(__file__).resolve().parent

# MESSY_DATA_PATH 指向“未清洗、结构混乱”的医疗文本。
# 这个文件故意把多个疾病主题挤在一起，方便观察数据质量差时的问题。
MESSY_DATA_PATH = BASE_DIR / "data" / "messy_medical_text.txt"

# CLEAN_DATA_PATH 指向“预处理后、结构清晰”的 Markdown 医疗文本。
# 这个文件使用标题、段落、小节把知识组织清楚，更适合后续切分。
CLEAN_DATA_PATH = BASE_DIR / "data" / "clean_medical_text.md"


def preview_text(title, path, max_length=600):
    """
    读取并预览文本内容。

    参数说明：
    title：打印到控制台的标题，用来区分当前预览的是混乱数据还是清洗数据。
    path：要读取的文件路径，是一个 Path 对象。
    max_length：最多预览多少个字符，默认 600，避免一次打印太多内容。
    """

    # read_text() 会读取整个文本文件。
    # encoding="utf-8" 用于正确读取中文内容。
    text = path.read_text(encoding="utf-8")

    # 打印一个分隔标题，让控制台输出更容易阅读。
    print(f"\n===== {title} =====")

    # 打印文件路径，帮助学习者知道当前内容来自哪个文件。
    print(f"文件路径: {path}")

    # len(text) 统计文本字符数。
    # 注意这里是字符数，不是 token 数。
    print(f"字符数量: {len(text)}")

    # text[:max_length] 只打印前 max_length 个字符。
    # 这适合做预览，不适合做完整数据处理。
    print(text[:max_length])


def main():
    """对比混乱医疗文本和预处理后医疗文本的差异。"""

    # 预览混乱文本。
    # 观察点：有没有标题、段落、标点、主题边界。
    preview_text("混乱数据集", MESSY_DATA_PATH)

    # 预览清洗后的 Markdown 文本。
    # 观察点：是否有疾病主题、小节标题、段落结构。
    preview_text("预处理后的结构化数据集", CLEAN_DATA_PATH)

    # 这里不是程序必须逻辑，而是教学提示。
    # 目的是让学习者带着问题去观察数据。
    print("\n观察重点：")
    print("1. 混乱文本缺少标题、段落和主题边界。")
    print("2. 结构化文本把疾病、建议、风险提示拆成了清晰小节。")
    print("3. 清晰结构会让后续切分更稳定，检索更精准。")


# Python 脚本入口。
# 只有直接运行本文件时才会执行 main()。
# 如果这个文件被 import，main() 不会自动执行。
if __name__ == "__main__":
    main()
