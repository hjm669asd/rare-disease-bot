"""
程序运行流程图：

准备一个医疗问题
   ↓
准备一组错误检索结果
   ↓
准备一组正确检索结果
   ↓
分别打印并对比
   ↓
理解检索质量如何影响 RAG 回答

本脚本的教学目标：
通过对比错误检索和正确检索，理解 RAG 答案质量的上限取决于检索结果质量。
"""


def main():
    """演示检索质量差异。"""

    question = "高血压患者什么时候需要及时就医？"

    # 错误检索结果：主题和问题不匹配。
    bad_results = [
        "糖尿病患者应监测空腹血糖。",
        "普通感冒患者应注意休息。",
    ]

    # 正确检索结果：命中高血压主题，并包含及时就医条件。
    good_results = [
        "高血压患者如果出现明显头痛、胸闷、视物模糊，应及时就医。",
        "高血压患者应定期测量血压并记录变化。",
    ]

    print(f"用户问题: {question}")

    print("\n========== 错误检索结果 ==========")
    for result in bad_results:
        print(result)

    print("\n========== 正确检索结果 ==========")
    for result in good_results:
        print(result)

    # 观察重点：
    # 1. 如果检索结果是糖尿病或感冒，模型很难回答高血压问题。
    # 2. 正确结果应包含疾病、症状和处理建议。
    # 3. 检索质量优化是企业级 RAG 的基础。


if __name__ == "__main__":
    main()
