"""
程序运行流程图：

准备一组候选检索结果
   ↓
观察其中有多条相似饮食内容
   ↓
手动选择更有多样性的结果
   ↓
打印普通 top_k 和 MMR 思路下的结果
   ↓
理解 MMR 如何平衡相关性和多样性

本脚本的教学目标：
用简化示例理解 MMR：不要只返回重复内容，要覆盖多个角度。
"""


def main():
    """演示 MMR 的多样性思想。"""

    normal_top_k_results = [
        "高血压患者应减少钠盐摄入。",
        "高血压患者应少吃腌制食品。",
        "高血压患者应避免高盐零食。",
    ]

    mmr_like_results = [
        "高血压患者应减少钠盐摄入。",
        "高血压患者应定期监测血压。",
        "高血压患者出现胸闷、视物模糊，应及时就医。",
    ]

    print("========== 普通 top_k 结果 ==========")
    for result in normal_top_k_results:
        print(result)

    print("\n========== MMR 思路结果 ==========")
    for result in mmr_like_results:
        print(result)

    # 观察重点：
    # 1. 普通 top_k 可能都在讲少盐。
    # 2. MMR 思路会覆盖饮食、监测、危险信号。
    # 3. 医疗问答中，多样性可以帮助答案更全面。


if __name__ == "__main__":
    main()
